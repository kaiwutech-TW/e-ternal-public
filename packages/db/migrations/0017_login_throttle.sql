-- 登入節流：把「密碼可以無限次猜」這件事關掉（公網部署前的安全批次 ①之二）
--
-- 為什麼要做這一批：在此之前 POST /auth/login 完全沒有任何失敗計數或延遲——
-- scrypt 雜湊讓每次嘗試要幾十毫秒，但那只是把「每秒一萬次」降到「每秒數十次」，
-- 對六碼密碼而言仍然是幾天內就猜得完。內網（或 Tailscale 私網）時這件事的風險有限，
-- 因為打得到登入頁的人已經在信任網路裡；一旦上公網，它就是整套權限系統的第一個破口。
--
-- ★ 設計紀律：**節流是「滑動視窗計數」，不是「鎖定旗標」**。
--   鎖定旗標（users.locked_until 之類）有兩個問題：
--   ①它需要有人去解鎖——十人公司沒有 24 小時待命的管理者，週末被鎖就是週末不能用；
--   ②它把「暫時擋一下」變成「持久狀態」，而持久狀態會被忘記、會與 active 欄位語意打架。
--   滑動視窗自己會癒合：最舊的一次失敗滿 15 分鐘就自動退出視窗，不需要任何人動手。
--
-- ★ 為什麼同時記 username 與 source（來源位址），而且門檻差很多：
--   - username 桶擋的是「盯著某個帳號猜密碼」，門檻要緊（5 次）。
--   - source 桶擋的是「拿常見密碼掃過所有帳號」，門檻要鬆（30 次），因為**整間公司可能共用
--     同一個對外 IP**：門檻設緊會變成一個人打錯字打太多次，全公司一起登不進來。
--   - source 取不到時存空字串＝「不知道」，而查詢端會跳過空字串——寧可少擋一層，
--     也不要把所有來源不明的請求算成同一個來源，那等於「一個人被擋＝全部被擋」。
--
-- ★ 這張表不是稽核紀錄：它只為了計數而存在，過了視窗就會被清掉（查詢時順手刪，
--   與 sessions 清過期同一個做法）。「誰在什麼時候登入失敗」的長期紀錄屬於操作日誌，
--   是這個安全批次的另一項，不要把兩者混成一張表——混在一起的下場是
--   「為了保留稽核而不敢刪」與「為了計數而必須刪」互相打架。

CREATE TABLE login_failures (
  id serial PRIMARY KEY,
  username text NOT NULL,           -- 嘗試登入的帳號；帳號不存在時照記（否則「猜帳號」不受節流）
  source text NOT NULL DEFAULT '',  -- 來源位址，取不到時為空字串（見上）
  at timestamptz NOT NULL DEFAULT now()
);

-- 兩個桶各自的視窗查詢；at 放在後面是因為條件永遠是「某個 key + 時間範圍」
CREATE INDEX login_failures_username_at_idx ON login_failures (username, at);
CREATE INDEX login_failures_source_at_idx ON login_failures (source, at);

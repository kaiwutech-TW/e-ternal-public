-- 二階段驗證的「設定中」密鑰：把重新設定的中途狀態與已生效的密鑰分開
--
-- 為什麼補這一檔（0019 的實作缺陷，上線前對抗驗證抓到）：
-- 原本 POST /auth/totp/setup 直接把新密鑰寫進 totp_secret 並把 totp_enabled_at 清成 NULL。
-- 對「第一次啟用」是對的，對「換手機時重新設定」是災難——
-- 使用者按下重新設定、還沒用新手機驗證就關掉瀏覽器（或掃描失敗、或臨時被叫走），
-- 這個帳號就**靜默掉回單因子**：舊手機上的條目因為密鑰被換掉而永遠對不上，
-- 新的又還沒生效，而畫面與登入流程都不會有任何徵兆——下次只要密碼就進得去。
-- 實測確認過：重設後未完成驗證，/auth/totp 回 enabled:false，純密碼登入拿到 200。
--
-- 修法是「設定中的密鑰另外放」：totp_secret 在驗證通過之前一個位元都不動。
-- 中途放棄的代價因此只剩下「pending 欄位留了一段沒用的密文」，而不是安全性靜默下降。
--
-- ★ 同一批一併補的另一個洞（在 app 層）：已啟用二階段驗證時，重新設定要**重新輸入密碼**。
--   不要求的話，拿到一個沒鎖螢幕的瀏覽器就能把第二因子換成自己的手機——
--   關閉功能已經要求密碼了，而重新設定的效果與「關閉再重開」完全相同。

ALTER TABLE users ADD COLUMN totp_pending_secret text;  -- 加密儲存；NULL＝目前沒有設定中的流程

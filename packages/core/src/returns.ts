/**
 * 退回／退出的金額攤分。規格書：docs/specs/posting-rules.md
 *
 * ── 一條總規則：退回＝撤銷原單的一部分，成本一律以「原單成本按數量比例攤」為基準，
 * 不追溯改寫另一端已完成的交易。
 *
 * 流入（銷貨退回：貨回到我們手上）回補原銷貨成本，不重算移動加權平均——
 * 因為 onHand() 就是庫存異動的線性加總，把原出庫的同一組 (qty, amount) 原封加回去，
 * 結果必然等於「那次出庫從未發生」。改用退貨當下的平均成本會把持有期間的進價漲跌
 * 當成本期損益：7/01 進 100@10、7/05 賣 40（成本 400）、7/10 進 60@20、7/20 退那 40 個——
 * 用原成本 400 回補後均價 13.75，與「假如 7/05 根本沒賣」完全一致；
 * 用當下均價 15 則回補 600，銷貨成本被沖 600 但當初只認 400，7 月毛利憑空虛增 200。
 *
 * 流出（進貨退出：貨離開我們手上）沖回原進貨成本，同樣是「假如那次進貨少進了這些」。
 *
 * 這裡曾經改用「退出當下的移動平均 × 數量」，差額進 5101，理由是「差額＝已售商品的成本更正」。
 * 那是錯的：**一件都沒賣過時這個前提不成立**。進 50@10 ＋ 50@2（均價 6）一件沒賣，
 * 退貴那批 50 個（退款 500）→ 用均價沖 300、差額 200 貸 5101，
 * 結果零營收卻有 200 元淨利，而存貨還留著 300（手上其實是那 50 個 2 元的貨，只值 100）。
 * 沖原成本 500 則存貨剩 100、均價 2、差額 0，帳與實際一致。
 *
 * 唯一的例外是**退光庫存**：此時沒有存貨可以承載差額，殘值必須清到 5101，
 * 否則留下「0 個卻有帳面金額」——進 100@10 再進 100@2、賣掉 100 個（成本 600）後
 * 退便宜那批 100 個（原成本 200），若只沖 200 則庫存 0 個卻背 400 元，
 * 下一筆進貨 10 個 @1 的均價就成了 41（真實 1），之後每筆銷貨成本都錯到底。
 * 退光時沖掉整個帳面 600，差額 200 − 600 = −400 借 5101：
 * 銷貨成本由 600 補到 1000，正是已售那 100 個的真實成本（總購入 1200 − 退款 200）。
 * 因此差額是**雙向**的，但只在退光時才會不為零。
 */
import { roundHalfUp } from "./money.ts";

/**
 * 依數量比例攤原單金額（金額或成本皆適用），退到最後一個單位時軋平為「原額 − 已退額」。
 *
 * 軋平不是潔癖：原明細 qty=3、cost=10（單位成本 3.3333），分三次各退 1 個，
 * 每次 round(10 × 1 / 3) = 3，合計只回補 9——存貨永遠短少 1 元，而且沒有任何報表會叫。
 * 軋平後最後一次退的是 10 − 3 − 3 = 4。
 */
export function prorateByQty(opts: {
  originalAmount: number;
  originalQty: number;
  priorQty: number; // 本次之前已退的數量
  priorAmount: number; // 本次之前已退的金額
  returnQty: number;
}): number {
  const { originalAmount, originalQty, priorQty, priorAmount, returnQty } = opts;
  if (originalQty <= 0) throw new Error(`原明細數量須為正: ${originalQty}`);
  if (priorQty + returnQty >= originalQty) return originalAmount - priorAmount;
  return roundHalfUp((originalAmount * returnQty) / originalQty);
}

/**
 * 進貨折讓要沖減多少存貨帳面金額：折讓金額 × 這批貨的未售比例（上限 1）。
 *
 * 折讓時貨不動，所以沒有「出庫成本」可算；供應商少收的錢有一部分屬於還躺在倉庫裡的貨
 * （該調降它的帳面成本），另一部分屬於已經賣掉的貨（該回沖銷貨成本）。
 * 比例的分母是原進貨明細數量，分子是「這批貨還剩幾個沒賣」。移動平均法下帳上不追蹤批次，
 * 沒有欄位能精確回答這件事，所以用 **FIFO 消耗推定**：算這批貨進來之後該商品出庫了多少
 * （庫存異動的 id 是遞增序號，取該筆進貨異動之後的出庫量加總），剩餘＝原數量 − 已消耗。
 * 這是近似，明確記錄於 docs/specs/posting-rules.md。
 *
 * 為什麼不能用「商品當下在庫數量」當分子（原本的寫法，2026-07-30 實測踩到）：
 * 進 100@10 → 賣光（在庫 0）→ 又進 100@1（在庫 100）→ 這時供應商對帳後才給明細 A 折讓 800。
 * 用當下在庫 100 ÷ 原數量 100 = 比例 1，折讓被整筆攤到「別批貨」上，再被在庫帳面 100 削平
 * → 在庫變成 100 個／0 元（均價 0），之後每筆銷貨成本都是 0。
 * 而 A 批其實早就賣光了，折讓 800 全屬已售貨，正解是不沖存貨、整筆回沖銷貨成本。
 * 供應商對帳後才給折讓是最常見的時序，這個誤判會反覆發生。
 *
 * 為什麼也不能先把在庫帳面吃光再轉銷貨成本：進 100@10、賣 50（成本 500）後在庫 50 個／500 元，
 * 供應商折讓 800 若先沖存貨就會沖光 500，在庫變成 50 個／0 元（均價 0）。
 * 按比例攤（消耗 50、剩 50 → 0.5）則沖 400、轉 400 到 5101，
 * 在庫 50 個／100 元＝均價 2，正是真實淨成本 (1000 − 800) / 100。
 */
export function allowanceInvCredit(opts: {
  allowance: number; // 本次折讓金額（未稅、正整數元）
  purchasedQty: number; // 原進貨明細數量
  /** 這批貨進來之後，該商品出庫了多少（FIFO 消耗推定，見下方說明） */
  consumedSincePurchase: number;
}): number {
  const { allowance, purchasedQty, consumedSincePurchase } = opts;
  if (purchasedQty <= 0) throw new Error(`原明細數量須為正: ${purchasedQty}`);
  const remaining = Math.max(0, purchasedQty - Math.max(0, consumedSincePurchase));
  const ratio = Math.min(1, remaining / purchasedQty);
  return roundHalfUp(allowance * ratio);
}

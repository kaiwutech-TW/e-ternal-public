export function guideIndex(): string {
  return AGENT_GUIDES.map((g) => `- ${g.name}：${g.title}`).join("\n");
}

export function readGuide(name: string): string | null {
  const g = AGENT_GUIDES.find((x) => x.name === name);
  return g ? `# ${g.title}\ntags: ${g.tags}\n\n${g.body}` : null;
}
